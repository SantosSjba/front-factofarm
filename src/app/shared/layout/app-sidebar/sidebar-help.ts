/** Texto de ayuda de una opción del menú (vacío si no tiene). */
export function sidebarHelp(item: NavItem | NavSubItem): string {
  if (item.path && PATH_HELP[item.path]) return PATH_HELP[item.path];
  const key = (item as NavItem).key;
  if (key && GROUP_HELP[key]) return GROUP_HELP[key];
  return SUBGROUP_HELP[item.name] ?? '';
}
